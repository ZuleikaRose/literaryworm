#!/usr/bin/env python3
"""Writes the migration that seeds legal_pages from the app's built-in copy.

Usage: python3 supabase/build-legal-seed.py
Reads front_end/literaryworm_app/src/data/legalPages.json and writes
supabase/migrations/20261028001704_seed_legal_pages.sql. Existing rows are left
alone (on conflict do nothing), so admins' edits are never overwritten.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
pages = json.loads((ROOT / "front_end/literaryworm_app/src/data/legalPages.json").read_text())
out = ROOT / "supabase/migrations/20261028001704_seed_legal_pages.sql"


def quote(text: str) -> str:
    # Dollar quoting, with a tag that can't appear in the text.
    tag = "$lw$"
    assert tag not in text
    return f"{tag}{text}{tag}"


rows = []
for position, page in enumerate(pages):
    sections = json.dumps(page.get("sections", []), ensure_ascii=False)
    rows.append(f"  ({quote(page['slug'])}, {position}, {quote(page['title'])}, {quote(page['summary'])}, {quote(sections)}::jsonb)")

out.write_text(
    "-- The legal pages' first copy, from the app's built-in text (generated by\n"
    "-- supabase/build-legal-seed.py; don't edit by hand). Admins edit them afterwards.\n\n"
    "insert into public.legal_pages (slug, position, title, summary, sections) values\n"
    + ",\n".join(rows)
    + "\non conflict (slug) do nothing;\n"
)
print(f"wrote {out.relative_to(ROOT)} ({len(pages)} pages)")
