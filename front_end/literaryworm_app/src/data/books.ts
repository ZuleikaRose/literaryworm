export const bookById = new Map(books.map((b) => [b.id, b]));

export function getBook(id: string | undefined): Book | undefined {
  return id ? bookById.get(id) : undefined;
}

const ratingOrder: Record<AgeRating, number> = { kids: 0, teen: 1, all: 2 };

/** True if a profile with `profileRating` may see a title rated `bookRating`. */
export function isAllowed(bookRating: AgeRating, profileRating: AgeRating): boolean {
  return ratingOrder[bookRating] <= ratingOrder[profileRating];
}

export function listenMinutes(b: Book): number {
  return b.chapters.reduce((sum, ch) => sum + ch.minutes, 0);
}

